#!/usr/bin/env python3
"""data/blocked_words.json -> supabase/migrations/20261021000002_blocklist.sql (the nickname blocklist the database
enforces; the game reads the same JSON through NickFilter). Run after editing the list, then `npx supabase db push`
(a changed list needs a new migration file name: pass it as the first argument)."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
words = json.loads((root / "data/blocked_words.json").read_text())["words"]
name = sys.argv[1] if len(sys.argv) > 1 else "20261021000002_blocklist.sql"
rows = ",\n".join("  ('%s', %s)" % (w.lstrip("="), "true" if w.startswith("=") else "false") for w in words)
sql = f"""-- generated by tools/make_blocklist_sql.py from data/blocked_words.json: do not edit by hand
delete from public.blocked_words;
insert into public.blocked_words (word, exact) values
{rows};
"""
(root / "supabase/migrations" / name).write_text(sql)
print(f"{len(words)} words -> supabase/migrations/{name}")
