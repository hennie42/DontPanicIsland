"""make_shore_field.py: assets/generated/shore_field.png + scripts/shore_field.gd, the distance from each point of the sea to the
island's beach (world units, 0 at the land's edge, clipped at MAXD), for the ocean shader's shallows, foam and calm
water near the shore. The island is fixed (data/island.json), so this runs offline once.
Run from the project: python3 tools/make_shore_field.py
"""
import json
import math

import numpy as np
from PIL import Image

N = 512            # texture size
MARGIN = 9.0       # sea around the island's bounding box, world units
MAXD = 6.0         # distances beyond this are "deep sea"
WIDTH = 1.0
SIZE = WIDTH / math.sqrt(3.0)
ROW = SIZE * 1.5

land = json.load(open("data/island.json"))["land"]
cx = np.array([WIDTH * (c["q"] + c["r"] * 0.5) for c in land])
cz = np.array([ROW * c["r"] for c in land])
minx, maxx = cx.min() - MARGIN, cx.max() + MARGIN
minz, maxz = cz.min() - MARGIN, cz.max() + MARGIN
size = max(maxx - minx, maxz - minz)
xs = minx + (np.arange(N) + 0.5) / N * size
zs = minz + (np.arange(N) + 0.5) / N * size
px, pz = np.meshgrid(xs, zs)               # row = z, column = x
best = np.full(px.shape, np.inf)


def hex_sd(dx, dz):
    """Exact signed distance to a pointy-top hexagon with inradius 0.5 (Inigo Quilez's sdHexagon; his hexagon has
    its flat sides at y = +-r, ours at x = +-0.5, so his y is our x)."""
    r = 0.5
    kx, ky, kz = -0.866025404, 0.5, 0.577350269
    px_, py_ = np.abs(dz), np.abs(dx)
    dot = np.minimum(kx * px_ + ky * py_, 0.0)
    px_ = px_ - 2.0 * dot * kx
    py_ = py_ - 2.0 * dot * ky
    qx = px_ - np.clip(px_, -kz * r, kz * r)
    qy = py_ - r
    return np.sqrt(qx * qx + qy * qy) * np.sign(qy)


for i in range(len(cx)):
    best = np.minimum(best, hex_sd(px - cx[i], pz - cz[i]))
d = np.clip(best, 0.0, MAXD) / MAXD
Image.fromarray((d * 255).round().astype(np.uint8)).save("assets/generated/shore_field.png")
# the field's placement, as a constant the game reads (a .json would not be exported with the game)
open("scripts/shore_field.gd", "w").write(
    "class_name ShoreField\n## Generated by tools/make_shore_field.py: where assets/generated/shore_field.png lies.\n"
    f"const RECT := Vector4({minx:.4f}, {minz:.4f}, {size:.4f}, {MAXD:.1f})   # min x, min z, size, max distance\n")
print(f"wrote assets/generated/shore_field.png: {N}x{N} over {size:.1f} units, land cells {len(cx)}")
